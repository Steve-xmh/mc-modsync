#!/usr/bin/env bash
# make-mod.sh <out.jar> <modId> [payload]
# Creates a fake NeoForge mod jar carrying META-INF/neoforge.mods.toml, for tests.
set -euo pipefail

out="$1"
modid="$2"
payload="${3:-$modid}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/META-INF"

cat > "$work/META-INF/neoforge.mods.toml" <<EOF
modLoader="javafml"
loaderVersion="[1,)"
license="MIT"

[[mods]]
modId="$modid"
version="1.0.0"
displayName="$modid"
description="fake mod generated by make-mod.sh (payload: $payload)"
EOF

# Payload makes the file content change between generations so hashes differ.
echo "$payload" > "$work/payload.txt"
mkdir -p "$out/.." 2>/dev/null || true
jar --create --file "$out" -C "$work" .
